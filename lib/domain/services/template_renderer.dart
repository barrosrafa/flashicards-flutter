import '../models/card_template.dart';

/// Renders Anki-compatible and Flashi card templates (`{{Field}}`, `{{#Cond}}...{{/Cond}}`,
/// `{{^Neg}}...{{/Neg}}`, `{{cloze:Text}}`, `{{type:Field}}`, and `{{FrontSide}}`).
///
/// Mirrors `src/lib/services/template-renderer.ts` from `app-flashi`.
class TemplateRenderer {
  const TemplateRenderer._();

  static final RegExp _positiveConditionalRegex = RegExp(
    r'\{\{#([a-zA-Z0-9_-]+)\}\}([\s\S]*?)\{\{\/\1\}\}',
  );
  static final RegExp _negativeConditionalRegex = RegExp(
    r'\{\{\^([a-zA-Z0-9_-]+)\}\}([\s\S]*?)\{\{\/\1\}\}',
  );
  static final RegExp _clozeTagRegex = RegExp(
    r'\{\{c(\d+)::([\s\S]*?)(?:::([\s\S]*?))?\}\}',
  );
  static final RegExp _clozeFieldDirectiveRegex = RegExp(
    r'\{\{cloze:([a-zA-Z0-9_-]+)\}\}',
  );
  static final RegExp _typeInDirectiveRegex = RegExp(
    r'\{\{type:([a-zA-Z0-9_-]+)\}\}',
  );
  static final RegExp _standardFieldRegex = RegExp(
    r'\{\{([a-zA-Z0-9_-]+)\}\}',
  );

  /// Extracts distinct cloze deletion indices (`1, 2, ...`) found in [text].
  static List<int> extractClozeIndices(String text) {
    final Set<int> indices = <int>{};
    for (final RegExpMatch match in _clozeTagRegex.allMatches(text)) {
      final int? idx = int.tryParse(match.group(1) ?? '');
      if (idx != null && idx > 0) {
        indices.add(idx);
      }
    }
    final List<int> sorted = indices.toList()..sort();
    return sorted;
  }

  /// Renders a single template string for the given [fields], [side] (`'front'` or `'back'`),
  /// and optional [activeClozeIndex] (1-based).
  static String renderSide({
    required String templateHtml,
    required Map<String, String> fields,
    required String side,
    String? renderedFrontHtml,
    int activeClozeIndex = 1,
  }) {
    String output = templateHtml;

    // 1. Replace {{FrontSide}} on the back template
    if (side == 'back' && renderedFrontHtml != null) {
      output = output.replaceAll('{{FrontSide}}', renderedFrontHtml);
    }

    // 2. Evaluate positive conditional blocks {{#Field}}...{{/Field}}
    output = output.replaceAllMapped(_positiveConditionalRegex, (Match m) {
      final String fieldKey = m.group(1)!;
      final String inner = m.group(2) ?? '';
      final String value = (fields[fieldKey] ?? '').trim();
      return value.isNotEmpty ? inner : '';
    });

    // 3. Evaluate negative conditional blocks {{^Field}}...{{/Field}}
    output = output.replaceAllMapped(_negativeConditionalRegex, (Match m) {
      final String fieldKey = m.group(1)!;
      final String inner = m.group(2) ?? '';
      final String value = (fields[fieldKey] ?? '').trim();
      return value.isEmpty ? inner : '';
    });

    // 4. Evaluate {{cloze:FieldName}}
    output = output.replaceAllMapped(_clozeFieldDirectiveRegex, (Match m) {
      final String fieldKey = m.group(1)!;
      final String rawField = fields[fieldKey] ?? '';
      return renderClozeText(
        rawText: rawField,
        activeClozeIndex: activeClozeIndex,
        revealAnswer: side == 'back',
      );
    });

    // 5. Evaluate {{type:FieldName}}
    output = output.replaceAllMapped(_typeInDirectiveRegex, (Match m) {
      final String fieldKey = m.group(1)!;
      final String expected = fields[fieldKey] ?? '';
      if (side == 'front') {
        return '[TYPE:$fieldKey]';
      }
      return expected;
    });

    // 6. Replace standard {{FieldName}} placeholders
    output = output.replaceAllMapped(_standardFieldRegex, (Match m) {
      final String fieldKey = m.group(1)!;
      if (fieldKey == 'FrontSide') {
        return renderedFrontHtml ?? '';
      }
      return fields[fieldKey] ?? '';
    });

    // 7. Also evaluate inline {{c1::...}} directly inside fields if not using {{cloze:...}}
    if (_clozeTagRegex.hasMatch(output)) {
      output = renderClozeText(
        rawText: output,
        activeClozeIndex: activeClozeIndex,
        revealAnswer: side == 'back',
      );
    }

    return output.trim();
  }

  /// Renders cloze tags inside [rawText] for [activeClozeIndex].
  static String renderClozeText({
    required String rawText,
    required int activeClozeIndex,
    required bool revealAnswer,
  }) {
    return rawText.replaceAllMapped(_clozeTagRegex, (Match m) {
      final int index = int.tryParse(m.group(1) ?? '1') ?? 1;
      final String answer = m.group(2) ?? '';
      final String? hint = m.group(3);

      if (index == activeClozeIndex) {
        if (revealAnswer) {
          return '**[$answer]**';
        }
        final String label = (hint != null && hint.trim().isNotEmpty)
            ? '[...${hint.trim()}...]'
            : '[...]';
        return label;
      }
      // Inactive cloze deletions show their text normally
      return answer;
    });
  }

  /// Renders all cards generated by [rules] for the given [fields].
  static List<RenderedCard> renderCards({
    required Map<String, String> fields,
    required List<CardGenerationRule> rules,
    bool isCloze = false,
  }) {
    if (isCloze) {
      final String combinedText = fields.values.join('\n');
      final List<int> clozeIndices = extractClozeIndices(combinedText);
      final List<int> effectiveIndices =
          clozeIndices.isEmpty ? const <int>[1] : clozeIndices;
      final CardGenerationRule primaryRule = rules.isNotEmpty
          ? rules.first
          : const CardGenerationRule(
              name: 'Cloze',
              frontTemplate: '{{cloze:Text}}',
              backTemplate: '{{cloze:Text}}\n\n{{Extra}}',
            );

      return effectiveIndices.map((int clozeOrd) {
        final String front = renderSide(
          templateHtml: primaryRule.frontTemplate,
          fields: fields,
          side: 'front',
          activeClozeIndex: clozeOrd,
        );
        final String back = renderSide(
          templateHtml: primaryRule.backTemplate,
          fields: fields,
          side: 'back',
          renderedFrontHtml: front,
          activeClozeIndex: clozeOrd,
        );
        return RenderedCard(
          ruleName: '${primaryRule.name} $clozeOrd',
          frontHtml: front,
          backHtml: back,
        );
      }).toList(growable: false);
    }

    return rules.map((CardGenerationRule rule) {
      final String front = renderSide(
        templateHtml: rule.frontTemplate,
        fields: fields,
        side: 'front',
      );
      final String back = renderSide(
        templateHtml: rule.backTemplate,
        fields: fields,
        side: 'back',
        renderedFrontHtml: front,
      );
      return RenderedCard(
        ruleName: rule.name,
        frontHtml: front,
        backHtml: back,
      );
    }).toList(growable: false);
  }
}
